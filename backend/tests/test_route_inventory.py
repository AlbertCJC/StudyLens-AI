def test_route_inventory_is_unchanged(app_instance):
    actual = {
        (rule.rule, ",".join(sorted(rule.methods - {"HEAD", "OPTIONS"})))
        for rule in app_instance.url_map.iter_rules()
    }
    assert actual == EXPECTED_RULES
